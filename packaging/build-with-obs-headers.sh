#!/usr/bin/env bash
#
# Builds the plugin without a libobs development package.
#
# Why this exists: most distributions do not ship libobs-dev, so the plugin is
# compiled against the REAL libobs headers taken from the obs-studio sources,
# and linked against a tiny import stub that carries the proper SONAME
# (libobs.so.N).  The resulting plugin has DT_NEEDED libobs.so.N and resolves
# every libobs symbol at load time from the OBS installation itself - which is
# exactly how a plugin built against libobs-dev behaves.
#
# Usage:
#   packaging/build-with-obs-headers.sh [--prefix <dir>] [--build-dir <dir>]
#   packaging/build-with-obs-headers.sh --prefix ~/.config/obs-studio
#
# Environment:
#   OBS_TAG       obs-studio tag to take the headers from (default: 33.0.1)
#   SIMDE_TAG     simde tag (only needed on x86 without native SSE headers)
#   CACHE_DIR     where the sources are cloned (default: ~/.cache/bongobs-cat)
#   JOBS          parallel build jobs (default: nproc)
#
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
OBS_TAG="${OBS_TAG:-33.0.1}"
SIMDE_TAG="${SIMDE_TAG:-v0.8.2}"
CACHE_DIR="${CACHE_DIR:-$HOME/.cache/bongobs-cat}"
JOBS="${JOBS:-$(nproc 2>/dev/null || echo 4)}"

BUILD_DIR=""
PREFIX=""
LIBOBS_SONAME="libobs.so.30"

usage() {
	sed -n '3,26p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'
}

while [[ $# -gt 0 ]]; do
	case "$1" in
	--prefix)
		PREFIX="${2:?--prefix needs a directory}"
		shift 2
		;;
	--prefix=*)
		PREFIX="${1#--prefix=}"
		shift
		;;
	--build-dir)
		BUILD_DIR="${2:?--build-dir needs a directory}"
		shift 2
		;;
	--build-dir=*)
		BUILD_DIR="${1#--build-dir=}"
		shift
		;;
	-h | --help)
		usage
		exit 0
		;;
	*)
		echo "error: unknown option '$1'" >&2
		usage >&2
		exit 2
		;;
	esac
done

BUILD_DIR="${BUILD_DIR:-$REPO_ROOT/build-release}"

say() { printf '==> %s\n' "$*"; }

# ---------------------------------------------------------------------------
# 1. libobs headers
# ---------------------------------------------------------------------------
mkdir -p "$CACHE_DIR"
OBS_SRC="$CACHE_DIR/obs-studio"
if [[ ! -f "$OBS_SRC/libobs/obs-module.h" ]]; then
	say "Fetching libobs headers from obs-studio $OBS_TAG"
	rm -rf "$OBS_SRC"
	git clone --depth 1 --branch "$OBS_TAG" --filter=blob:none --sparse \
		https://github.com/obsproject/obs-studio.git "$OBS_SRC"
	git -C "$OBS_SRC" sparse-checkout set libobs
else
	say "Using cached libobs headers ($OBS_SRC)"
fi

# ---------------------------------------------------------------------------
# 2. simde (obs.h pulls in util/sse-intrin.h on non-MSVC toolchains)
# ---------------------------------------------------------------------------
SIMDE_SRC="$CACHE_DIR/simde"
if [[ ! -f "$SIMDE_SRC/simde/x86/sse2.h" ]]; then
	say "Fetching simde $SIMDE_TAG"
	rm -rf "$SIMDE_SRC"
	git clone --depth 1 --branch "$SIMDE_TAG" --filter=blob:none \
		https://github.com/simd-everywhere/simde.git "$SIMDE_SRC"
else
	say "Using cached simde ($SIMDE_SRC)"
fi

# ---------------------------------------------------------------------------
# 3. import stub package (headers + a libobs.so.N with the right SONAME)
# ---------------------------------------------------------------------------
STUB="$CACHE_DIR/obs-stub"
mkdir -p "$STUB/include" "$STUB/lib/cmake/libobs"

cat > "$STUB/include/obsconfig.h" <<'EOF'
/* Minimal obsconfig.h: normally generated by the obs-studio CMake build. */
#pragma once
#define OBS_INSTALL_PREFIX "/usr"
#define OBS_DATA_PATH "share/obs"
#define OBS_PLUGIN_PATH "lib/obs-plugins"
#define OBS_PLUGIN_DESTINATION "lib/obs-plugins"
#define OBS_RELEASE_CANDIDATE 0
#define OBS_BETA 0
EOF

# The stub only has to carry the symbols; the real implementation is provided
# by the OBS installation at load time.  Keep this list in sync with the
# sources - a new libobs call shows up as an undefined symbol at link time.
cat > "$STUB/stub.c" <<'EOF'
void *obs_current_module;
#define STUB(name) void name(void) {}
STUB(obs_module_text)
STUB(obs_data_get_bool)
STUB(obs_data_get_double)
STUB(obs_data_get_int)
STUB(obs_data_get_string)
STUB(obs_data_set_default_bool)
STUB(obs_data_set_default_double)
STUB(obs_data_set_default_int)
STUB(obs_data_set_default_string)
STUB(obs_enter_graphics)
STUB(obs_find_module_file)
STUB(obs_get_video_info)
STUB(obs_leave_graphics)
STUB(obs_module_load_locale)
STUB(obs_properties_add_bool)
STUB(obs_properties_add_float_slider)
STUB(obs_properties_add_list)
STUB(obs_properties_create)
STUB(obs_properties_set_param)
STUB(obs_property_list_add_string)
STUB(obs_register_source_s)
STUB(obs_source_draw)
STUB(gs_texture_create)
STUB(gs_texture_destroy)
STUB(gs_texture_map)
STUB(gs_texture_unmap)
STUB(bfree)
STUB(blog)
STUB(text_lookup_destroy)
STUB(text_lookup_getstr)
EOF

say "Building the libobs import stub ($LIBOBS_SONAME)"
gcc -shared -fPIC -Wl,-soname,"$LIBOBS_SONAME" -o "$STUB/lib/$LIBOBS_SONAME" "$STUB/stub.c"
ln -sf "$LIBOBS_SONAME" "$STUB/lib/libobs.so"

cat > "$STUB/lib/cmake/libobs/libobsConfig.cmake" <<EOF
add_library(OBS::libobs SHARED IMPORTED)
set_target_properties(OBS::libobs PROPERTIES
  IMPORTED_LOCATION "$STUB/lib/$LIBOBS_SONAME"
  INTERFACE_INCLUDE_DIRECTORIES "$OBS_SRC/libobs;$STUB/include;$SIMDE_SRC")
EOF

# ---------------------------------------------------------------------------
# 4. build the plugin
# ---------------------------------------------------------------------------
say "Configuring ($BUILD_DIR)"
cmake -S "$REPO_ROOT" -B "$BUILD_DIR" \
	-DCMAKE_BUILD_TYPE="${BUILD_TYPE:-Release}" \
	-DCMAKE_PREFIX_PATH="$STUB" \
	-DCMAKE_SKIP_BUILD_RPATH=ON

say "Building"
cmake --build "$BUILD_DIR" -j"$JOBS"

if [[ -n "$PREFIX" ]]; then
	say "Installing into $PREFIX"
	cmake --install "$BUILD_DIR" --prefix "$PREFIX"
fi

say "Done: $BUILD_DIR/bongobs-cat.so"
